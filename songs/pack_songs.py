#!/usr/bin/env python3
"""Pack your songs for offline play (opening index.html directly from disk).
Put mp3/ogg/wav/m4a files in this folder. Optional metadata, either:
  * my-song.json next to my-song.mp3:  {"title":"My Song","bpm":128,"offset":0.12,"diff":2}
  * or entries in songs.json:          {"songs":[{"title":"My Song","file":"my-song.mp3","bpm":128,"offset":0.12}]}
bpm/offset are optional (the game estimates them). offset = seconds to the first downbeat. diff = 2 or 3.
Then run:  python3 pack_songs.py   -> writes user-songs.js (the game auto-loads it).
"""
import base64, json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
MIME = {".mp3": "audio/mpeg", ".ogg": "audio/ogg", ".wav": "audio/wav", ".m4a": "audio/mp4"}
meta = {}
try:
    for m in json.load(open(os.path.join(here, "songs.json"))).get("songs", []):
        if m.get("file") and "_example" not in m: meta[m["file"]] = m
except Exception: pass
out = []
for f in sorted(os.listdir(here)):
    ext = os.path.splitext(f)[1].lower()
    if ext not in MIME: continue
    m = dict(meta.get(f, {}))
    side = os.path.join(here, os.path.splitext(f)[0] + ".json")
    if os.path.exists(side):
        try: m.update(json.load(open(side)))
        except Exception as e: print("bad json", side, e)
    m.setdefault("title", os.path.splitext(f)[0])
    m.update(file=f, mime=MIME[ext], data=base64.b64encode(open(os.path.join(here, f), "rb").read()).decode())
    out.append(m); print("packed", f, "->", m["title"])
# split into chunks (each chunk file goes into its own dist zip, < 24 MB)
LIMIT = 17_000_000
chunks, cur, size = [], [], 0
for m in out:
    n = len(m["data"])
    if cur and size + n > LIMIT: chunks.append(cur); cur, size = [], 0
    cur.append(m); size += n
if cur or not chunks: chunks.append(cur)
for f in os.listdir(here):
    if f.startswith("user-songs-") and f.endswith(".js"): os.remove(os.path.join(here, f))
names = ["user-songs-%d.js" % (i + 1) for i in range(len(chunks))]
index = []
for nm, ch in zip(names, chunks):
    with open(os.path.join(here, nm), "w") as fh:
        fh.write("// Generated by pack_songs.py\nwindow.USER_SONGS=(window.USER_SONGS||[]).concat(" + json.dumps(ch) + ");\n")
    for m in ch:
        st = {k: v for k, v in m.items() if k not in ("data", "ons")}; st["chunk"] = nm; st["stub"] = 1; index.append(st)
    print(nm, len(ch), "song(s)", round(os.path.getsize(os.path.join(here, nm)) / 1e6, 1), "MB")
with open(os.path.join(here, "user-songs.js"), "w") as fh:
    fh.write("// Generated by pack_songs.py: song index; audio chunks are loaded on demand\nwindow.USER_SONG_PARTS=[];\nwindow.USER_SONGS=" + json.dumps(index) + ";\n")
print(len(out), "song(s) written")
